use std::fmt::Display;

#[derive(Debug, Clone, PartialEq)]
pub enum Opcode {
    Add,
    LoadConstant(usize),
    Print(usize),
    Pop,
    Abs,
    Nagetive,
    JumpNotTruthy(usize),
    Jump(usize),
    Null,
    ReturnValue,
    SetGlobal(usize),
    GetGlobal(usize),
    SetLocal(usize),
    GetLocal(usize),
    GetBuiltin(usize),
    Closure(usize, usize),
    GetFree(usize),
    CurrentClosure,
    Call(usize),
    TailCall(usize),
    Return,
    Array(usize),
    Hash(usize),
    Index,
    SetIndex,
    True,
    False,
    Equal,
    JumpIfFalse(usize),
    NotEqual,
    GreaterThan,
    LessThan,
    GreaterThanEqual,
    LessThanEqual,
    Minus,
    Mod,
    Divide,
    Multiply,
    Remainder,
    Bang,
    MinusOne,
    PlusOne,
    DefineGlobal(String),
    Assert(usize),
    EqualEqual,
    Exit(usize),
}


impl Display for Opcode {

    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Opcode::Add => write!(f, "{}", 0x1),
            Opcode::LoadConstant(index) => write!(f, "{}",  0x2 << 31 | index),
            Opcode::Print(index) => write!(f, "{}", 0x3 << 31 | index),
            Opcode::Pop => write!(f, "{}", 0x4),
            Opcode::Abs => write!(f, "{}", 0x5),
            Opcode::Nagetive => write!(f, "{}", 0x6),
            Opcode::JumpNotTruthy(pos) => write!(f, "{}", 0x7 << 31 | pos),
            Opcode::Jump(pos) => write!(f, "{}", 0x8 << 31 | pos),
            Opcode::Null => write!(f, "{}", 0x9),
            Opcode::ReturnValue => write!(f, "{}", 0xA),
            Opcode::SetGlobal(index) => write!(f, "{}", 0xB << 31 | index),
            Opcode::GetGlobal(index) => write!(f, "{}", 0xC << 31 | index),
            Opcode::SetLocal(index) => write!(f, "{}", 0xD << 31 | index),
            Opcode::GetLocal(index) => write!(f, "{}", 0xE << 31 | index),
            Opcode::GetBuiltin(index) => write!(f, "{}", 0xF << 31 | index),
            Opcode::Closure(index, free) => write!(f, "{}", 0x10 << 31 | index << 16 | free),
            Opcode::GetFree(index) => write!(f, "{}", 0x11 << 31 | index),
            Opcode::CurrentClosure => write!(f, "{}", 0x12),
            Opcode::Call(count) => write!(f, "{}", 0x13 << 31 | count),
            Opcode::TailCall(count) => write!(f, "{}", 0x14 << 31 | count),
            Opcode::Return => write!(f, "{}", 0x15),
            Opcode::Array(size) => write!(f, "{}", 0x16 << 31 | size),
            Opcode::Hash(size) => write!(f, "{}", 0x17 << 31 | size),
            Opcode::Index => write!(f, "{}", 0x18),
            Opcode::SetIndex => write!(f, "{}", 0x19),
            Opcode::True => write!(f, "{}", 0x1A),
            Opcode::False => write!(f, "{}", 0x1B),
            Opcode::Equal => write!(f, "{}", 0x1C),
            Opcode::JumpIfFalse(pos) => write!(f, "{}", 0x1D << 31 | pos),
            Opcode::NotEqual => write!(f, "{}", 0x1E),
            Opcode::GreaterThan => write!(f, "{}", 0x1F),
            Opcode::LessThan => write!(f, "{}", 0x20),
            Opcode::GreaterThanEqual => write!(f, "{}", 0x21),
            Opcode::LessThanEqual => write!(f, "{}", 0x22),
            Opcode::Minus => write!(f, "{}", 0x23),
            Opcode::Mod => write!(f, "{}", 0x24),
            Opcode::Divide => write!(f, "{}", 0x25),
            Opcode::Multiply => write!(f, "{}", 0x26),
            Opcode::Remainder => write!(f, "{}", 0x27),
            Opcode::Bang => write!(f, "{}", 0x28),
            Opcode::MinusOne => write!(f, "{}", 0x29),
            Opcode::PlusOne => write!(f, "{}", 0x2A),
            Opcode::DefineGlobal(_) => write!(f, "{}", 0x2B << 31),
            Opcode::Assert(pos) => write!(f, "{}", 0x2C << 31 | pos),
            Opcode::EqualEqual => write!(f, "{}", 0x2D),
            Opcode::Exit(code) => write!(f, "{}", 0x2E << 31 | code),
        }
    }

}
